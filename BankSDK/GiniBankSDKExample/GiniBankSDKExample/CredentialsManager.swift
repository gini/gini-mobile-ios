import Foundation
import GiniBankAPILibrary

/**
 Builds `Client` instances from the compile-time `Credentials` enum
 generated by `scripts/generate_credentials.sh` on every build.
 */
final class CredentialsManager {

    class func fetchClientFromBundle() -> Client {
        Client(id: Credentials.clientID,
               secret: Credentials.clientPassword,
               domain: Credentials.clientDomain)
    }

    class func fetchCXClientFromBundle() -> Client {
        Client(id: Credentials.cxClientID,
               secret: Credentials.cxClientPassword,
               domain: Credentials.clientDomain)
    }

    class func fetchStageClientFromBundle() -> Client {
        Client(id: Credentials.stageClientID,
               secret: Credentials.stageClientPassword,
               domain: Credentials.clientDomain)
    }
}
